"""Generate assets/js/india-map.js (run from the repo root, after build-geo.py)

Usage: python3 scripts/build-region-map.py
 — region map geometry for the Optional PYQs page.

Regions are unions of states (documented regional groups used for filtering,
not official physiographic boundaries). Boundary data: udit-001/india-maps-data
(DataMeet-derived district boundaries), dissolved to states, simplified and
projected to Albers equal-area by build_geo.py.
"""
import json

m = json.load(open('geo/india_states.json'))
states = {s['name']: s for s in m['states']}

REGIONS = [
    ("himalaya", "Himalayan Belt",
     ["Jammu and Kashmir", "Ladakh", "Himachal Pradesh", "Uttarakhand", "Sikkim", "Arunachal Pradesh"]),
    ("plain", "Indo-Gangetic Plain",
     ["Punjab", "Haryana", "Chandigarh", "Delhi", "Uttar Pradesh", "Bihar", "West Bengal"]),
    ("desert", "Thar & Aravalli", ["Rajasthan"]),
    ("plateau", "Peninsular Plateau",
     ["Madhya Pradesh", "Chhattisgarh", "Jharkhand", "Maharashtra", "Telangana", "Karnataka"]),
    ("west-coast", "Western Coast",
     ["Gujarat", "Goa", "Kerala", "Dadra and Nagar Haveli and Daman and Diu"]),
    ("east-coast", "Eastern Coast",
     ["Odisha", "Andhra Pradesh", "Tamil Nadu", "Puducherry"]),
    ("northeast", "North-East",
     ["Assam", "Meghalaya", "Manipur", "Mizoram", "Nagaland", "Tripura"]),
    ("islands", "Islands", ["Andaman and Nicobar Islands", "Lakshadweep"]),
]

KEYWORDS = {
    "himalaya": ["himalaya", "trans-himalaya", "kashmir", "ladakh", "jammu", "uttarakhand", "kumaon",
                 "garhwal", "himachal", "sikkim", "arunachal", "dun valley", "shivalik", "siwalik", "karewa"],
    "plain": ["plain", "plains", "ganga", "ganges", "gangetic", "punjab", "haryana", "delhi",
              "uttar pradesh", "bihar", "doab", "bhangar", "khadar", "terai", "bhabar"],
    "desert": ["thar", "desert", "rajasthan", "aravalli", "arid"],
    "plateau": ["plateau", "peninsular", "peninsula", "deccan", "chota nagpur", "chhotanagpur", "malwa",
                "vindhya", "satpura", "madhya pradesh", "chhattisgarh", "jharkhand", "maharashtra",
                "telangana", "karnataka", "bundelkhand", "baghelkhand", "gondwana"],
    "west-coast": ["west coast", "konkan", "malabar", "gujarat", "kachchh", "kutch", "kathiawar",
                   "saurashtra", "goa", "kerala", "western ghats", "sahyadri"],
    "east-coast": ["east coast", "coromandel", "utkal", "andhra", "tamil nadu", "odisha", "orissa",
                   "chilika", "godavari delta", "krishna delta", "cauvery delta", "mahanadi delta"],
    "northeast": ["north-east", "northeast", "assam", "meghalaya", "manipur", "mizoram", "nagaland",
                  "tripura", "shillong", "barak", "brahmaputra"],
    "islands": ["andaman", "nicobar", "lakshadweep", "island"],
}

zones = []
used = set()
for rid, name, members in REGIONS:
    d = " ".join(states[s]['d'] for s in members if s in states)
    used.update(members)
    zones.append({"id": rid, "name": name, "keywords": KEYWORDS[rid], "d": d})

assert set(states) == used, set(states) ^ used

out = {
    "viewBox": m["viewBox"],
    "source": ("udit-001/india-maps-data (DataMeet-derived district boundaries), dissolved to "
               "states, simplified, Albers equal-area"),
    "zones": zones,
    "borders": [states[k]['d'] for k in sorted(states)],
}

js = (
    "/* India region map geometry — generated by scripts/build-region-map.py, do not hand-edit.\n"
    " * Boundary source: " + out["source"] + ".\n"
    " * Each zone is the union of its states: a documented regional grouping used to\n"
    " * filter questions, not an official physiographic boundary.\n"
    " */\n"
    "window.INDIA_MAP = " + json.dumps(out, separators=(',', ':')) + ";\n"
)
open('assets/js/india-map.js', 'w').write(js)
print("bytes", len(js), "zones", len(zones))
